def timing(img, g, quiet=False):
    """A/B instruction counts at equal lengths and different scalars.

    THE SCALAR IS THE PRIVATE KEY.  Both ladders here are fixed-shape by
    construction - EcPointMul does two doublings and one addition per
    2-bit window whatever the window holds, and X25519 runs 255
    iterations whatever the scalar is - so a difference in the model's
    instruction count means a branch or an index read the key.  The
    cases hold the LENGTH fixed and make the VALUE as different as it
    can be: all-zero bits, all-one bits, one bit at the top, one at the
    bottom, and a mixed pattern.
    """
    scalars = [bytes(32),
               b"\xff" * 32,
               b"\x80" + bytes(31),
               bytes(31) + b"\x01",
               bytes((i * 37 + 11) & 0xFF for i in range(32))]
    # TEN INDEPENDENT RUNS, SO THEY GO ACROSS THE POOL.  One P-256 scalar
    # multiply is about 26 million model instructions and one X25519 is
    # about 35 million; ten of them in one process is a third of a
    # billion, which is the kind of serial gate that gets killed for
    # running for hours.  Nothing is shared between them.
    peer = g.enc_point(g.pt_mul(0x2B, g.G))
    ec_args, x_args = [], []
    for sc in scalars:
        s = Script()
        s.add(OP_NEG, "ct-ec", b0=peer, b1=sc)     # verdict only, no output
        ec_args.append((img.read_bytes(), s.done(), len(s), s._o))
        s = Script()
        s.add(OP_X25519, "ct-x", b0=sc, b1=X_BASE9, out=bytes(32))
        x_args.append((img.read_bytes(), s.done(), len(s), s._o))

    args = ec_args + x_args
    nw = max(1, min(len(args), JOBS_CAP or (os.cpu_count() or 2) - 2))
    if nw == 1:
        steps = [run_raw(*a)[2] for a in args]
    else:
        with concurrent.futures.ProcessPoolExecutor(max_workers=nw) as ex:
            steps = [r[2] for r in ex.map(_worker, args)]
    counts_ec = steps[:len(ec_args)]
    counts_x = steps[len(ec_args):]

    rc = 0
    if len(set(counts_ec)) != 1:
        rc = 1
        if not quiet:
            print("FAIL: EcP256Mul executed %s instructions for five "
                  "32-byte scalars that differ only in VALUE - the private "
                  "key is visible in the timing" % (counts_ec,))
    if len(set(counts_x)) != 1:
        rc = 1
        if not quiet:
            print("FAIL: X25519 executed %s instructions for five 32-byte "
                  "scalars that differ only in VALUE - the private key is "
                  "visible in the timing" % (counts_x,))
    if rc:
        if not quiet:
            print("CT GATE RED")
        return 1
    if not quiet:
        print("CT GATE GREEN: EcP256Mul %d instructions and X25519 %d "
              "instructions for all %d scalars at the same length"
              % (counts_ec[0], counts_x[0], len(scalars)))
    return 0


