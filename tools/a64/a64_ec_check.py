X_BASE9 = bytes([9] + [0] * 31)


# =====================================================================
#  THIS GATE'S TWO DERIVED CASES, AND THE SWEEP IS WHY THEY EXIST
# =====================================================================
#  Both were added on 2026-09-05 because the mutation sweep went RED with
#  two survivors that the table said must die - M6 and M12.  Neither was
#  a hole in the library: each was a CHECK THAT NO VECTOR REACHED, which
#  is the same failure the A64 GCM sweep found four times over.  Nothing
#  below is transcribed; both are computed from the generator's own
#  constants and its own anchored oracle.
def derived_range_point(g):
    """$04 || p || sqrt(B) - the one non-canonical encoding on this curve
    whose REDUCTION is a real point, so only the range check can refuse it.

    The shared set's "X = p" negative does not reach the range check.  It
    keeps the original Y, so after the mutation deletes "coordinate < p"
    the decoder reduces X = p to 0 and asks whether (0, Y) is on the
    curve - it is not, the on-curve test refuses it anyway, and M6 lives.

    P-256's b is a QUADRATIC RESIDUE mod p, so (0, sqrt(b)) IS on the
    curve: y^2 = 0^3 - 3*0 + b.  Encoding that point's X as p instead of
    0 gives a value that is >= p and whose reduction is legitimate, so
    the range check is the ONLY thing standing between it and an accept.
    p = 3 mod 4, so the root is b^((p+1)/4).

    This is the only such encoding available.  Every other non-canonical
    X is p + x for x < 2^256 - p, which is under 2^224, and finding an
    on-curve point with an X that small is a 2^32 search.
    """
    if g.P % 4 != 3:
        return None
    y = pow(g.B, (g.P + 1) // 4, g.P)
    if (y * y - g.B) % g.P != 0 or not g.on_curve(0, y):
        return None
    return b"\x04" + g.P.to_bytes(32, "big") + y.to_bytes(32, "big")


def derived_unclamped_scalar(g, sc):
    """KAT 0's scalar with bit 254 CLEARED, which the clamp must put back.

    RFC 7748's clamp is k[0] &= 248; k[31] &= 127; k[31] |= 64.  Every
    scalar in the shared table already has bit 254 set, so the `|= 64`
    is a no-op on all of them and M12 - which deletes it - survives.

    Clearing that one bit costs NOTHING in expectations: the generator's
    own oracle clamps before it computes, so it returns the SAME answer
    for this scalar as for the original, and the case reuses KAT 0's
    published output unchanged.  A library that clamps correctly agrees;
    one that has lost the `|= 64` runs a different ladder and does not.
    """
    if not (sc[31] & 0x40):
        return None                      # already clear - nothing to prove
    out = bytearray(sc)
    out[31] &= ~0x40
    return bytes(out)


def build_script(g, level="full", iter1000=False):
    """level: "full" or "mutant" (cheap, but must still reach every line)."""
    mulgen, mul, ecdh, neg = g.build_ec256()
    kats, iters = g.build_x25519()
    s = Script()
    mutant = (level == "mutant")

    if mutant:
        # THE MUTANT SUBSET IS A TIME DECISION AND IT HAS ONE HARD
        # REQUIREMENT: every line a mutation can be planted in must still
        # be reached.  A full 32-byte scalar is 128 ladder windows and
        # about 65 million model instructions; a ONE-BYTE scalar is four
        # windows and reaches the identical code, because the ladder is a
        # fixed loop over the scalar's bytes.  The short-scalar
        # expectations come from the generator's OWN anchored oracle
        # (pt_mul), so they are not a second source of truth.
        #
        # Everything that is not the ladder is kept in full: the two
        # carry KATs already use a one-byte scalar, and all four
        # negatives run, because the decoder is where most of the
        # mutations live.
        short = bytes([0x2B])
        base = g.pt_mul(0x2B, g.G)
        s.add(OP_MULGEN, "mulgen (short scalar $2B)", b0=short,
              out=g.enc_point(base), scalars=(65, None))
        for i, (pin, k, pout, r) in enumerate(mul):
            s.add(OP_MUL, "mul KAT %d" % i, b0=pin, b1=k, out=pout,
                  scalars=(r, None))
        priv, peer, sx, r = ecdh[0]
        peer_pt = (int.from_bytes(peer[1:33], "big"),
                   int.from_bytes(peer[33:65], "big"))
        s.add(OP_ECDH, "ecdh (short private $2B)", b0=short, b1=peer,
              out=g.pt_mul(0x2B, peer_pt)[0].to_bytes(32, "big"),
              scalars=(1, None))
        for i, (pt, k, r) in enumerate(neg):
            s.add(OP_NEG, "negative %d (must be REFUSED)" % i, b0=pt,
                  b1=short, scalars=(0, None))
        sc, u, out = kats[0]
        s.add(OP_X25519, "x25519 RFC 7748 KAT 1", b0=sc, b1=u, out=out,
              scalars=(1, None))
        add_derived(s, g, kats, short)
        return s

    for i, (k, pt) in enumerate(mulgen):
        s.add(OP_MULGEN, "mulgen %d (%d-byte scalar)" % (i, len(k)),
              b0=k, out=pt, scalars=(65, None))
    for i, (pin, k, pout, r) in enumerate(mul):
        s.add(OP_MUL, "mul %d (the BearSSL P256 carry KAT)" % i,
              b0=pin, b1=k, out=pout, scalars=(r, None))
    for i, (priv, peer, sx, r) in enumerate(ecdh):
        s.add(OP_ECDH, "ecdh %d (shared X)" % i, b0=priv, b1=peer,
              out=sx, scalars=(r, None))
    for i, (pt, k, r) in enumerate(neg):
        s.add(OP_NEG, "negative %d (must be REFUSED: %s)"
              % (i, NEG_WHY[i] if i < len(NEG_WHY) else "?"),
              b0=pt, b1=k, scalars=(r, None))
    for i, (sc, u, out) in enumerate(kats):
        s.add(OP_X25519, "x25519 %d" % i, b0=sc, b1=u, out=out,
              scalars=(1, None))

    add_derived(s, g, kats, mulgen[0][0])

    # The RFC 7748 iterated tests.  One iteration always; a thousand only
    # on demand - see the module docstring.
    s.add(OP_XITER, "x25519 iterated, 1 round (RFC 7748 5.2)", a0=1,
          b0=X_BASE9, out=X_ITER1)
    if iters and iters[0][1] != X_ITER1:
        raise SystemExit("the generator's 1-iteration value is not the "
                         "published RFC 7748 one; the table changed under "
                         "this gate")
    if iter1000:
        s.add(OP_XITER, "x25519 iterated, 1000 rounds (RFC 7748 5.2)",
              a0=1000, b0=X_BASE9, out=X_ITER1000)
    return s


NEG_WHY = [
    "off the curve, one bit flipped in Y",
    "wrong uncompressed prefix $06",
    "coordinate X = p, not less than p",
    "the origin encoded as $04 || 0 || 0",
]


def add_derived(s, g, kats, scalar):
    """The two cases the 2026-09-05 sweep proved were missing.

    Both are in EVERY level, including the mutant subset, because the
    mutations they exist to kill are decoder mutations and the subset
    already keeps every negative for that reason.  Neither costs a
    ladder the subset was not already running.
    """
    pt = derived_range_point(g)
    if pt is None:
        raise SystemExit(
            "the derived range-check negative could not be built from the "
            "generator's own constants (p mod 4, or b is no longer a "
            "quadratic residue). This gate will not silently drop the only "
            "case that reaches the 'coordinate < p' test - see M6.")
    s.add(OP_NEG, "derived negative: X = p with Y = sqrt(b), the one "
                  "non-canonical encoding whose REDUCTION is on the curve "
                  "(only the range check can refuse it)",
          b0=pt, b1=scalar, scalars=(0, None))

    sc, u, out = kats[0]
    unclamped = derived_unclamped_scalar(g, sc)
    if unclamped is None:
        raise SystemExit(
            "KAT 0's scalar no longer has bit 254 set, so clearing it "
            "proves nothing about the clamp. Pick another KAT deliberately "
            "rather than letting this case become a no-op - see M12.")
    s.add(OP_X25519, "derived: RFC 7748 KAT 1 with the scalar's bit 254 "
                     "CLEARED - the clamp must put it back, so the answer "
                     "is unchanged", b0=unclamped, b1=u, out=out,
          scalars=(1, None))


