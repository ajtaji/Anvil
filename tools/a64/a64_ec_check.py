#!/usr/bin/env python3
"""Executable gate for RaspberryPi4/Lib/ec256.pi4 and
RaspberryPi4/Lib/x25519.pi4 - the M8 elliptic-curve primitives on AArch64.

WHY THIS FILE IS WRITTEN THE WAY IT IS

  THE VECTORS ARE THE ONES THE PICO GATES ALREADY USE.  They are not
  transcribed here and they are not generated here: this gate IMPORTS
  build_ec256() and build_x25519() out of tools/gen_ec_vectors.py, the
  file that emits ec256Vectors.pico2 and x25519Vectors.pico2 for the
  three 32-bit families.  That generator ANCHORS its own oracle first -
  it aborts unless a dependency-free Python EC implementation reproduces
  the published NIST/BearSSL P-256 generator KAT and the RFC 7748 X25519
  KAT exactly - so the expectations arrive already checked against
  published constants.  One table, four families.

  THE TWO BUILDERS ARE CALLED IN THE GENERATOR'S OWN ORDER, ec256 then
  x25519, and that is not cosmetic: they draw from one seeded
  random.Random, so calling them the other way round would produce a
  DIFFERENT, self-consistent, and quietly non-shared vector set.

  THE NEGATIVES ARE THE POINT.  Four of them, and each is a different
  way an attacker-supplied point can be wrong: off the curve (one bit
  flipped in Y), the wrong uncompressed prefix ($06 instead of $04), a
  coordinate that is not less than p (X = p exactly), and the origin
  encoded as $04 || 0 || 0.  EcP256Mul must return 0 for every one.  A
  gate with only positive vectors goes green on a decoder that never
  refuses anything, and an EC library that accepts an off-curve point is
  how a private key leaves the building.

  THE 1000-ITERATION X25519 TEST IS NOT RUN HERE, AND THAT HOLE IS
  DECLARED RATHER THAN HIDDEN.  One X25519 is about 35 million model
  instructions; a thousand of them is 35 billion, which is a day under
  this oracle for a test whose value is repetition.  The ONE-iteration
  RFC 7748 iterated case IS run, against the published
  422c8e7a... expectation.  --iter1000 runs the full one for anybody
  willing to wait, and the summary line says which of the two ran.

  IT RUNS ON ALL CORES.  The image is built ONCE and the job list is
  sharded across a process pool; every worker runs the same image over
  its own slice.  --jobs overrides.

WHAT THIS GATE DOES NOT SAY

  * That any of this runs on silicon.  The oracle is a model of the
    instruction set: no caches, no memory system, no clock.
  * That the implementation is constant time ON HARDWARE.  --timing
    checks that the MODEL executes the identical number of instructions
    for scalars of wholly different content at the same length, which
    rules out a data-dependent branch or a secret-indexed access in the
    compiled code.  It says nothing about what a real Cortex-A72 does.

Run: python tools/a64/a64_ec_check.py
     python tools/a64/a64_ec_check.py --timing
     python tools/a64/a64_ec_check.py --mutate
"""

