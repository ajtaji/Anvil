# =====================================================================
#  THE HARNESS
# =====================================================================
#  SCRIPT RECORD - a 28-byte header, then blob0 || blob1, padded to 4:
#      +0 op  +4 a0  +8 a1  +12 n0  +16 n1  +20 outlen  +24 (spare)
#  RESULT RECORD - 32 bytes, FOUR 64-BIT FIELDS:
#      +0 scalar0 (the verdict)  +8 scalar1  +16 outlen  +24 spare
#
#  THE VERDICT FIELD IS 64 BITS AND THAT IS NOT DECORATION.  The A64 GCM
#  gate stored its verdicts with PokeN and the one mutation it existed
#  to catch survived, because the wrong value's set bits were all above
#  bit 31 and the low half read back clean.
# =====================================================================
HARNESS = r'''
; ======================================================================
;  echarness.pi4 - GENERATED BY tools/a64/a64_ec_check.py.
;  NOT A SOURCE FILE. DO NOT EDIT.
; ======================================================================
XIncludeFile "RaspberryPi4/Lib/uart.pi4"
XIncludeFile "RaspberryPi4/Lib/bignum.pi4"
XIncludeFile "__EC256__"
XIncludeFile "__X25519__"

#H_SCRIPT = $06000000
#H_RESULT = $0A000000
#H_OUT    = $0B000000

; The point buffer is `.a` - EcP256Mul writes 65 raw bytes into it.
Global Dim EhPt.a[80]
Global Dim EhK.a[40]
Global Dim EhOut.a[40]
Global Dim EhU.a[40]

Procedure.i Main()
  Define p.i
  Define q.i
  Define o.i
  Define op.i
  Define a0.i
  Define a1.i
  Define n0.i
  Define n1.i
  Define outlen.i
  Define b0.i
  Define b1.i
  Define s0.i
  Define s1.i
  Define i.i
  Define n.i

  EcInit()
  X25519Init()

  p = #H_SCRIPT
  q = #H_RESULT
  o = #H_OUT

  Repeat
    op     = PeekN(p)
    a0     = PeekN(p + 4)
    a1     = PeekN(p + 8)
    n0     = PeekN(p + 12)
    n1     = PeekN(p + 16)
    outlen = PeekN(p + 20)
    If op = 0
      Break
    EndIf
    b0 = p + 28
    b1 = b0 + n0

    s0 = 0
    s1 = 0

    ; The output area is pre-filled with a sentinel by the gate, so a
    ; refusal that writes anyway is as loud as a wrong byte.
    If op = 1
      ; MULGEN - dst = k * G.
      s0 = EcP256Mulgen(@EhPt[0], b0, n0)
      i = 0
      While i < outlen
        PokeB(o + i, EhPt[i])
        i = i + 1
      Wend

    ElseIf op = 2
      ; MUL - pt = k * pt, in place, 65 bytes.
      i = 0
      While i < 65
        EhPt[i] = PeekA(b0 + i) & 255
        i = i + 1
      Wend
      s0 = EcP256Mul(@EhPt[0], 65, b1, n1)
      i = 0
      While i < outlen
        PokeB(o + i, EhPt[i])
        i = i + 1
      Wend

    ElseIf op = 3
      ; ECDH - the shared secret is the X coordinate of priv * peer,
      ; which is bytes 1..32 of the multiplied point.
      i = 0
      While i < 65
        EhPt[i] = PeekA(b1 + i) & 255
        i = i + 1
      Wend
      s0 = EcP256Mul(@EhPt[0], 65, b0, n0)
      i = 0
      While i < outlen
        PokeB(o + i, EhPt[1 + i])
        i = i + 1
      Wend

    ElseIf op = 4
      ; NEG - a point that must be REFUSED. Only the verdict is read.
      i = 0
      While i < 65
        EhPt[i] = PeekA(b0 + i) & 255
        i = i + 1
      Wend
      s0 = EcP256Mul(@EhPt[0], 65, b1, n1)

    ElseIf op = 5
      ; X25519 - out = scalar * u, all 32-byte little-endian.
      s0 = X25519(@EhOut[0], b0, b1)
      i = 0
      While i < outlen
        PokeB(o + i, EhOut[i])
        i = i + 1
      Wend

    ElseIf op = 6
      ; XITER - the RFC 7748 iterated test, a0 iterations from k = u = 9.
      i = 0
      While i < 32
        EhK[i] = PeekA(b0 + i) & 255
        EhU[i] = PeekA(b0 + i) & 255
        i = i + 1
      Wend
      n = 0
      While n < a0
        X25519(@EhOut[0], @EhK[0], @EhU[0])
        i = 0
        While i < 32
          EhU[i] = EhK[i]
          EhK[i] = EhOut[i]
          i = i + 1
        Wend
        n = n + 1
      Wend
      i = 0
      While i < outlen
        PokeB(o + i, EhK[i])
        i = i + 1
      Wend
    EndIf

    PokeI(q, s0)
    PokeI(q + 8, s1)
    PokeI(q + 16, outlen)
    PokeI(q + 24, 0)

    p = p + 28 + n0 + n1
    p = ((p + 3) / 4) * 4
    q = q + 32
    o = o + (((outlen + 3) / 4) * 4)
  ForEver

  UartWriteStr("echarness done")
  ProcedureReturn 0
EndProcedure
'''


