def build(lib_include: str, harness: pathlib.Path, img: pathlib.Path) -> None:
    WORK.mkdir(exist_ok=True)
    harness.write_text(patch_harness(HARNESS.replace("__LIB__",
                                                 lib_include),
                                 globals()),
                       encoding="utf-8")
    cmd = [str(PMFC), "--compile", str(harness), "-t", TFLAG,
           "--load-addr", hex(LOAD), "--stack-addr", hex(STACK),
           "--entry-returns", "-o", str(img)]
    r = subprocess.run(cmd, cwd=ROOT, env=BUILD_ENV, text=True,
                       stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    if r.returncode != 0 or "pmfc: OK" not in r.stdout:
        raise SystemExit("build failed:\n" + r.stdout)


def run(img: pathlib.Path, script: bytes, count: int):
    blob = img.read_bytes()
    cpu = A64()
    mem = cpu.memory
    for i, b in enumerate(blob):
        mem[LOAD + i] = b
    for i, b in enumerate(script):
        mem[H_SCRIPT + i] = b
    cpu.pc = LOAD
    cpu.sp = LOADER_SP
    cpu.x[30] = LOADER_LR

    uart = bytearray()

    def load(addr, size):
        if UART_LO <= addr <= UART_HI:
            return 0                       # a PL011 that is never busy
        return sum(mem.get(addr + i, 0) << (8 * i) for i in range(size))

    def store(addr, value, size):
        if UART_LO <= addr <= UART_HI:
            if addr == UART_DR:
                uart.append(value & 0xFF)
            return
        for i in range(size):
            mem[addr + i] = (value >> (8 * i)) & 0xFF

    cpu.load = load
    cpu.store = store

    steps = 0
    while cpu.pc != LOADER_LR:
        cpu.step()
        steps += 1
        if steps > STEP_LIMIT:
            raise SystemExit("the harness never returned (%d steps)\n%s"
                             % (steps, uart.decode("latin-1")))

    if b"sha1harness done" not in uart:
        raise SystemExit("the harness returned without finishing its script:\n"
                         + uart.decode("latin-1"))

    out = []
    for i in range(count):
        a = H_RESULT + i * 20
        out.append(bytes(mem.get(a + j, 0) for j in range(20)))
    return out, steps


# =====================================================================
#  THE VECTOR SET
# =====================================================================
CHUNKS = (1, 3, 7, 64)


def build_script(million: bool, subset: bool = False) -> Script:
    """The full vector set, or - for the mutation sweep - a subset.

    THE SUBSET IS A TIME DECISION AND NOTHING ELSE.  The full set is
    578 vectors and 120 million model instructions, about four minutes;
    eleven mutations of that is three quarters of an hour and a sweep
    nobody runs is a sweep that does not exist.  The subset keeps every
    CAVP SHORT vector - which is every distinct padding case, 0 to 64
    bytes - both chunkings that matter, every seam, and the four
    longest CAVP long messages, and drops the 60 long vectors that only
    repeat a code path the others already cover.  If a future mutation
    turns out to be invisible to the subset, put it back on the full
    set rather than dropping the mutation.
    """
    s = Script()

    short = parse_cavp(CAVP_SHORT)
    for n, msg, md in short:
        s.add(OP_ONESHOT, "CAVP short len=%d one shot" % n, md, msg)
    for n, msg, md in short:
        for c in ((1, 64) if subset else CHUNKS):
            s.add(OP_CHUNKED, "CAVP short len=%d in %d-byte pieces" % (n, c),
                  md, msg, arg=c)

    # The seam cases.  Split points land before, in the middle of, and
    # one byte short of the message, so a snapshot taken with a full
    # partial block and one taken with an almost-empty one are both
    # covered.
    for n, msg, md in short:
        if n >= 2:
            for cut in sorted({1, n // 2, n - 1}):
                s.add(OP_SEAM,
                      "CAVP short len=%d snapshot at %d" % (n, cut),
                      md, msg, arg=cut)

    long_v = parse_cavp(CAVP_LONG)
    if subset:
        long_v = long_v[:2] + long_v[-2:]
    for n, msg, md in long_v:
        s.add(OP_ONESHOT, "CAVP long len=%d one shot" % n, md, msg)

    for name, unit, rep, md in parse_rfc3174():
        if rep > 1000 and not million:
            continue
        s.add(OP_REPEAT, "RFC 3174 %s (%d x %d bytes)"
              % (name, rep, len(unit)), md, unit, arg=rep)

    return s


def check(img: pathlib.Path, s: Script, quiet: bool = False) -> list[str]:
    got, steps = run(img, s.done(), len(s.labels))
    bad = []
    for i, label in enumerate(s.labels):
        if got[i] != s.expect[i]:
            bad.append("  %-46s expected %s\n  %-46s got      %s"
                       % (label, s.expect[i].hex(), "", got[i].hex()))
    if not quiet:
        print("  %d vectors, %s, %d steps"
              % (len(s.labels), "ALL PASS" if not bad else
                 "%d FAILED" % len(bad), steps))
    return bad


# =====================================================================
#  MUTATIONS
# =====================================================================
#  Each entry is (name, old, new, why).  `old` must occur EXACTLY the
#  number of times given by `count`, so a mutation that silently stops
#  applying - because the file was edited - is an error rather than a
#  free pass.
#  Each entry is (name, old, new, count, expect_red, why).  `old` must
#  occur EXACTLY `count` times, so a mutation that silently stops
#  applying - because the file was edited - is an error rather than a
#  free pass.
#
#  expect_red IS NOT A CONVENIENCE.  Three of the defects below are
#  PROVABLY INVISIBLE to any known-answer test, and the first sweep of
#  this gate found all three.  Deleting them would hide a real finding;
#  pretending they should go red would leave a permanent false alarm.
#  So each mutation records what it is EXPECTED to do, and the sweep
#  fails if a mutation deviates from its expectation IN EITHER
#  DIRECTION.  A mask that is currently unobservable becoming
#  observable is news, and this is the only way to hear it.
#
#  This is the same shape as sha256.pi4's variant scoreboard, arrived
#  at independently and for the same reason: the mask invariant in
#  these files is a REVIEWABILITY property, not a correctness one, and
#  saying so with evidence is worth more than claiming otherwise.
MUTATIONS = [
    ("stride 4 instead of 8",
     "#SHA1_HWORD = 8", "#SHA1_HWORD = 4", 1, True,
     "the 32-bit families' spelling, copied across unchanged: reads the "
     "high half of H[0] as H[1]"),

    # THE FIRST SPELLING OF THIS ONE WAS A NO-OP AND THE SWEEP SAID SO.
    # Swapping PeekA for PeekB on the byte that lands at bit 24, while
    # LEAVING its "& 255" in place, changes nothing: the mask cuts the
    # sign extension off before the shift.  Even without the mask, that
    # particular byte's sign extension lands entirely above bit 31,
    # where the round's own mask removes it.  The byte that actually
    # breaks the word is the LAST one, whose sign extension fills every
    # bit above 7 - so that is the one mutated.
    ("signed byte read, unmasked, low byte",
     "| (PeekA(blk + 3) & 255)", "| (PeekB(blk + 3))", 1, True,
     "PeekB sign-extends; the low byte's extension fills the whole word"),

    ("rotate loses its output mask",
     "ProcedureReturn ((x << n) | ((x & #SHA1_W32) >> (32 - n))) & #SHA1_W32",
     "ProcedureReturn ((x << n) | ((x & #SHA1_W32) >> (32 - n)))", 1, False,
     "PROVABLY UNOBSERVABLE ALONE. The rubbish left in bits 32..62 can "
     "only move upward - additions carry up, left shifts move up - and "
     "the one operation that could drag it down, the right half of the "
     "next rotate, masks its input first. Every value that leaves the "
     "algorithm leaves through '& 255' on a bit below 32"),

    ("rotate right half goes arithmetic",
     "((x & #SHA1_W32) >> (32 - n))", "((x) >> (32 - n))", 1, False,
     "PROVABLY UNOBSERVABLE ALONE. With the output mask still in place "
     "every value reaching Sha1Rotl is clean and non-negative, so an "
     "arithmetic shift and a logical one agree"),

    ("BOTH rotate masks removed at once",
     "ProcedureReturn ((x << n) | ((x & #SHA1_W32) >> (32 - n))) & #SHA1_W32",
     "ProcedureReturn ((x << n) | (x >> (32 - n)))", 1, True,
     "THIS IS WHY BOTH MASKS ARE THERE. Each is redundant given the "
     "other; neither is redundant given nothing. Remove both and dirt "
     "from bits 32..62 is dragged back down into the digest"),

    ("one wrong round constant",
     "+ $5A827999)", "+ $5A82799A)", 1, True,
     "a single-nibble typo in K(0..19)"),

    ("wrong f() in the third quarter",
     "Sha1Maj(b, c, d)", "Sha1Par(b, c, d)", 1, True,
     "rounds 40..59 must use majority, not parity"),

    ("padding spill test off by one",
     "If ptr > 56", "If ptr > 57", 1, True,
     "a 55-byte message would then write its length over the pad"),

    ("schedule rotates by two",
     "! Sha1W[i - 16], 1)", "! Sha1W[i - 16], 2)", 1, True,
     "S^1 in the message schedule is not S^2"),

    ("digest word order",
     "PokeB(dst + i * 4,     (Sha1OutH[i] >> 24) & 255)",
     "PokeB(dst + i * 4,     (Sha1OutH[i] >> 16) & 255)", 1, True,
     "the digest is big-endian; a shift of 16 duplicates a byte"),

    ("one round short",
     """  ; t = 60..79, K = $CA62C1D6 - rfc3174.txt:311
  While i < 80""",
     """  ; t = 60..79, K = $CA62C1D6 - rfc3174.txt:311
  While i < 79""", 1, True,
     "79 rounds instead of 80"),

    ("snapshot counter at the wrong offset",
     "PokeN(dst + 84, Sha1CountLo)", "PokeN(dst + 80, Sha1CountLo)", 1, True,
     "the counter would land in the last four bytes of the block image"),
]


def mutate(args) -> int:
    src = LIB.read_text(encoding="utf-8")
    s = build_script(million=False, subset=True)
    failures = 0
    print("MUTATION TEST - each defect must do what its expectation says")
    for name, old, new, count, expect_red, why in MUTATIONS:
        n = src.count(old)
        if n != count:
            print("  %-38s CANNOT APPLY - the anchor occurs %d times, "
                  "expected %d" % (name, n, count))
            print("        anchor: %r" % (old,))
            failures += 1
            continue
        mut = WORK / "sha1_mut.pi4"
        mut.write_text(src.replace(old, new), encoding="utf-8")
        red = None
        nbad = 0
        try:
            build("_work/sha1_mut.pi4", WORK / "sha1harness_mut.pi4",
                  WORK / "sha1check_mut.img")
        except SystemExit:
            red = True
            note = "refused to build"
        if red is None:
            try:
                bad = check(WORK / "sha1check_mut.img", s, quiet=True)
                nbad = len(bad)
                red = nbad > 0
                note = "%d of %d vectors" % (nbad, len(s.labels))
            except SystemExit:
                red = True
                note = "the harness did not complete"

        if red == expect_red:
            print("  %-38s %-5s (%s)" % (name, "RED" if red else "GREEN", note))
            if not expect_red:
                print("        expected green: %s" % why)
        else:
            failures += 1
            if expect_red:
                print("  %-38s *** GREEN - THE GATE DID NOT SEE IT *** %s"
                      % (name, why))
            else:
                print("  %-38s *** RED, AND IT WAS EXPECTED GREEN ***" % name)
                print("        The reasoning recorded for this mutation no "
                      "longer holds. That is a finding, not a failure of the")
                print("        library: read it, then update the note. Was: %s"
                      % why)
    return failures


def resolve_compiler(requested):
    """Resolve the PureMetal compiler the way tools/build.py does."""
    sys.path.insert(0, str(ROOT / "tools"))
    import build as anvil_build  # noqa: E402
    return anvil_build.find_compiler(requested)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--compiler", default=os.environ.get("PMF_COMPILER"),
                    help="path of PureMetalForge.exe (or set PMF_COMPILER); "
                         "it is run with --compile")
    ap.add_argument("--target", choices=sorted(TARGETS),
                    default="pi4",
                    help="which AArch64 board's image contract "
                         "to build and grade against")
    ap.add_argument("--mutate", action="store_true",
                    help="rebuild the library broken, one defect at a time, "
                         "and require this gate to go red for each")
    ap.add_argument("--million", action="store_true",
                    help="also run RFC 3174 TEST3, one million bytes; "
                         "minutes, not seconds")
    args = ap.parse_args()
    globals()["PMFC"] = resolve_compiler(args.compiler)
    apply_target(globals(), args.target)
    # A GATE THAT DOES NOT SAY WHICH BOARD IT GRADED IS A RESULT
    # THAT CAN BE FILED AGAINST THE WRONG ONE.  Printed before any
    # work, so it is at the top of the transcript even on a failure.
    print("[gate] target %s - %s, image at $%08X, stack $%08X"
          % (TARGET_NAME, TARGET_WHAT, LOAD, STACK))

    WORK.mkdir(exist_ok=True)

    if args.mutate:
        build("RaspberryPi4/Lib/sha1.pi4", WORK / "sha1harness.pi4",
              WORK / "sha1check.img")
        s = build_script(million=False, subset=True)
        bad = check(WORK / "sha1check.img", s)
        if bad:
            print("the unmutated library is already failing; fix that first")
            print("\n".join(bad[:10]))
            return 1
        return 1 if mutate(args) else 0

    t0 = time.time()
    build("RaspberryPi4/Lib/sha1.pi4", WORK / "sha1harness.pi4",
          WORK / "sha1check.img")
    s = build_script(args.million)
    print("SHA-1 gate - oracles: NIST CAVP SHA1ShortMsg/SHA1LongMsg, RFC 3174")
    bad = check(WORK / "sha1check.img", s)
    print("  %.1f s" % (time.time() - t0))
    if bad:
        print("\nFAILURES")
        print("\n".join(bad))
        return 1
    print("OK")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
