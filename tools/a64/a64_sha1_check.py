#!/usr/bin/env python3
"""Executable gate for RaspberryPi4/Lib/sha1.pi4.

WHY THIS FILE IS WRITTEN THE WAY IT IS

A hash has exactly one useful kind of test: a known-answer test against
answers somebody else computed.  A hash that agrees with itself is a
hash that agrees with its own bug, and on this target the bugs that
have actually happened - a stride of 4 on a 64-bit array, a signed
PeekB on a byte with bit 7 set - are all of the kind that produce a
deterministic, stable, repeatable, WRONG digest.  Nothing about the
output looks broken.  Only an independent oracle can tell.

  THE ORACLE IS NIST'S OWN.  Every expected digest in the main body of
  this gate is PARSED OFF THE DISK out of the NIST CAVP byte-oriented
  SHA test vectors, RaspberryPi4/Reference/cavp_SHA1ShortMsg.rsp and
  cavp_SHA1LongMsg.rsp.  Those files were generated by NIST for the
  Cryptographic Algorithm Validation Program.  Not one expected value
  in them was typed by anybody working on this project, and not one
  came from running sha1.pi4 and writing down what it said.

  THE SECOND ORACLE IS RFC 3174.  Its section 7.3 test driver carries
  four vectors from FIPS PUB 180-1, and they are parsed out of
  RaspberryPi4/Reference/rfc3174.txt - the messages out of its #define
  block and the digests out of its resultarray[] - rather than
  transcribed here.  A transcription is a chance to be wrong that the
  parse does not have.

  THE SHORT VECTORS ARE ALSO RUN SPLIT.  Every CAVP short message is
  fed in one shot and then again in 1-, 3-, 7- and 64-byte chunks.
  Streaming is the property most likely to be quietly broken by a
  partial-block bug and least likely to be caught by a one-shot test,
  because a one-shot test never exercises the partial-block path at
  all for messages under 64 bytes.

  SNAPSHOT AND RESTORE ARE PROVEN ACROSS A SEAM, and proven to be a
  real save: the harness snapshots mid-message, then deliberately
  destroys the live context by starting and running a whole other
  digest, then restores and finishes.  If Restore were a no-op the
  answer would be the wrong one, loudly.

  --mutate IS NOT OPTIONAL AND IT IS THE POINT.  This project has had
  four gates certify real bugs in one week because the model was more
  forgiving than the part.  --mutate rebuilds sha1.pi4 with one
  deliberate defect at a time - twelve of them, each a bug somebody
  could plausibly write - and requires each to behave the way the
  table says it will.  A gate nobody has watched fail is a gate nobody
  has a reason to believe.

  TEN OF THE TWELVE MUST GO RED.  TWO MUST GO GREEN, and that is
  recorded rather than hidden.  Two of the masks in Sha1Rotl turn out
  to be individually unobservable - each is redundant GIVEN THE OTHER -
  and a further mutation removes both at once and goes red, which is
  the evidence that neither is decoration.  The first sweep of this
  gate found all three, and the honest thing to do with a finding like
  that is write it down, not delete the mutation that produced it.
  The sweep fails if any mutation deviates from its expectation IN
  EITHER DIRECTION, so a mask that becomes observable later is news
  this gate will deliver.

WHAT THIS GATE DOES NOT SAY

  * That any of this runs on silicon.  tools/a64/a64_interp.py is a
    model of the instruction set, not of the BCM2711.  It has no
    caches and no real memory system.  The silicon evidence has to
    come from a board, and
    RaspberryPi4/Examples/Diagnostics/pi4WifiJoin.pi4 runs the same
    vectors there.
  * Anything about SHA-1's security.  SHA-1 is collision-broken and
    sha1.pi4's header says so at length.  This gate proves the file
    computes the function the standard defines, which is a different
    and much smaller claim.
  * The 1,000,000-byte RFC 3174 case, unless --million is passed.  It
    is 15,625 compressions against a Python model and takes minutes
    rather than seconds; it is the only vector here that reaches a
    byte count above 16 bits.

Run: python tools/a64/a64_sha1_check.py
     python tools/a64/a64_sha1_check.py --million
     python tools/a64/a64_sha1_check.py --mutate
"""

