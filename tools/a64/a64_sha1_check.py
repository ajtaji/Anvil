# =====================================================================
#  THE HARNESS
# =====================================================================
#  It reads a script of hash jobs out of memory at #H_SCRIPT, runs
#  them, and writes each 20-byte digest into #H_RESULT.  Every message
#  is DATA, so adding a vector never changes this file.
#
#  SCRIPT RECORD, 12 bytes then `ln` bytes of message, padded to 4:
#      +0 op   +4 arg   +8 ln   +12 message
#  op 0 ends the script.
#
#  RESULT RECORD: 20 bytes of digest, one per script record.
# =====================================================================
HARNESS = r'''
; ======================================================================
;  sha1harness.pi4 - GENERATED BY tools/a64/a64_sha1_check.py.
;  NOT A SOURCE FILE. DO NOT EDIT.
; ======================================================================
XIncludeFile "RaspberryPi4/Lib/uart.pi4"
XIncludeFile "__LIB__"

#H_SCRIPT = $06000000
#H_RESULT = $0A000000

Global Dim hSnap.a[92]
Global Dim hWaste.a[20]

Procedure.i Main()
  Define p.i
  Define q.i
  Define op.i
  Define arg.i
  Define ln.i
  Define blob.i
  Define off.i
  Define n.i
  Define r.i

  p = #H_SCRIPT
  q = #H_RESULT

  Repeat
    op  = PeekN(p)
    arg = PeekN(p + 4)
    ln  = PeekN(p + 8)
    If op = 0
      Break
    EndIf
    blob = p + 12

    If op = 1
      ; One shot.
      Sha1Of(blob, ln, q)

    ElseIf op = 2
      ; Streamed in fixed-size pieces. arg is the piece size.
      Sha1Begin()
      off = 0
      While off < ln
        n = arg
        If off + n > ln
          n = ln - off
        EndIf
        Sha1Update(blob + off, n)
        off = off + n
      Wend
      Sha1End(q)

    ElseIf op = 3
      ; Snapshot at byte arg, then DESTROY the live context with a
      ; whole other digest, then restore and finish. If Restore did
      ; nothing the answer would be the digest of the tail alone.
      Sha1Begin()
      If arg > 0
        Sha1Update(blob, arg)
      EndIf
      Sha1Snapshot(@hSnap[0])
      Sha1Begin()
      Sha1Update(blob, ln)
      Sha1End(@hWaste[0])
      Sha1Restore(@hSnap[0])
      If ln > arg
        Sha1Update(blob + arg, ln - arg)
      EndIf
      Sha1End(q)

    ElseIf op = 4
      ; The message is the blob repeated arg times. This is how the
      ; RFC 3174 cases with a repeat count are run without putting a
      ; million bytes into the model's memory.
      Sha1Begin()
      r = 0
      While r < arg
        Sha1Update(blob, ln)
        r = r + 1
      Wend
      Sha1End(q)
    EndIf

    p = p + 12 + (((ln + 3) / 4) * 4)
    q = q + 20
  ForEver

  UartWriteStr("sha1harness done")
  ProcedureReturn 0
EndProcedure
'''


class Script:
    """The byte stream the harness walks, plus a label per record so a
    failure can name itself."""

    def __init__(self) -> None:
        self.buf = bytearray()
        self.labels: list[str] = []
        self.expect: list[bytes] = []

    def add(self, op: int, label: str, expect: bytes, msg: bytes = b"",
            arg: int = 0) -> None:
        self.labels.append(label)
        self.expect.append(expect)
        self.buf += struct.pack("<III", op, arg, len(msg))
        self.buf += msg
        pad = (-len(msg)) % 4
        self.buf += b"\x00" * pad

    def done(self) -> bytes:
        return bytes(self.buf) + struct.pack("<III", OP_END, 0, 0)


# =====================================================================
#  THE ORACLES, READ OFF THE DISK
# =====================================================================
def parse_cavp(path: pathlib.Path) -> list[tuple[int, bytes, bytes]]:
    """Parse a NIST CAVP .rsp file into (bitlen, message, digest).

    The format is a run of `Len =` / `Msg =` / `MD =` triples.  The
    zero-length case writes `Msg = 00` and means the EMPTY message -
    that convention is NIST's, it is the single most commonly mis-read
    line in the file, and getting it wrong would silently drop the one
    vector that exercises the empty-message padding path.
    """
    if not path.exists():
        raise SystemExit(
            f"the oracle is missing: {path}\n"
            "It is the NIST CAVP byte-oriented SHA test vector set. Fetch\n"
            "shabytetestvectors.zip from csrc.nist.gov into "
            "RaspberryPi4/Reference/ - do not invent replacements.")
    out: list[tuple[int, bytes, bytes]] = []
    length = None
    msg = None
    for raw in path.read_text(errors="replace").splitlines():
        line = raw.strip()
        if line.startswith("Len ="):
            length = int(line.split("=", 1)[1])
            msg = None
        elif line.startswith("Msg ="):
            msg = bytes.fromhex(line.split("=", 1)[1].strip())
        elif line.startswith("MD ="):
            md = bytes.fromhex(line.split("=", 1)[1].strip())
            if length is None or msg is None:
                raise SystemExit(f"{path.name}: an MD with no Len/Msg before it")
            if length % 8:
                raise SystemExit(
                    f"{path.name}: Len={length} is not a whole number of "
                    "bytes. This is the BYTE-oriented vector set; a bit "
                    "count that is not a multiple of 8 means the wrong file "
                    "was downloaded.")
            n = length // 8
            body = b"" if n == 0 else msg
            if len(body) != n:
                raise SystemExit(
                    f"{path.name}: Len={length} but Msg is {len(body)} bytes")
            if len(md) != 20:
                raise SystemExit(f"{path.name}: an MD that is not 20 bytes")
            out.append((n, body, md))
            length = None
            msg = None
    if not out:
        raise SystemExit(f"{path.name}: no vectors parsed - has the format changed?")
    return out


def parse_rfc3174() -> list[tuple[str, bytes, int, bytes]]:
    """Parse the four FIPS 180-1 vectors out of RFC 3174 section 7.3.

    Returns (name, unit, repeat, digest).  The message is `unit`
    repeated `repeat` times - that is how the RFC's own driver states
    it, and keeping the shape means the 1,000,000-byte case does not
    have to exist as a literal anywhere.

    The messages come from the `#define TEST*` block and the digests
    from `resultarray[]`, both parsed rather than transcribed.  If the
    RFC is ever replaced by a different revision this raises instead of
    quietly testing nothing.
    """
    if not RFC3174.exists():
        raise SystemExit(
            f"the citation is missing: {RFC3174}\n"
            "sha1.pi4 cites it by line for every constant it contains.")
    text = RFC3174.read_text(errors="replace")

    defines: dict[str, str] = {}
    for name, body in re.findall(r"#define\s+(TEST\w*)\s+(.+)", text):
        body = body.strip()
        lits = re.findall(r'"((?:[^"\\]|\\.)*)"', body)
        if lits:
            defines[name] = "".join(
                l.replace("\\n", "\n").replace("\\\\", "\\") for l in lits)
        else:
            parts = body.split()
            if all(p in defines for p in parts):
                defines[name] = "".join(defines[p] for p in parts)

    m = re.search(r"repeatcount\[4\]\s*=\s*\{([^}]*)\}", text)
    if not m:
        raise SystemExit("rfc3174.txt: repeatcount[] is gone - find the new form")
    repeats = [int(x) for x in m.group(1).replace(",", " ").split()]

    m = re.search(r"resultarray\[4\]\s*=\s*\{([^}]*)\}", text, re.S)
    if not m:
        raise SystemExit("rfc3174.txt: resultarray[] is gone - find the new form")
    digests = [bytes.fromhex(s.replace(" ", ""))
               for s in re.findall(r'"([0-9A-Fa-f ]+)"', m.group(1))]

    if len(digests) != 4 or len(repeats) != 4:
        raise SystemExit("rfc3174.txt: expected four vectors, found "
                         f"{len(digests)} digests and {len(repeats)} counts")
    for d in digests:
        if len(d) != 20:
            raise SystemExit("rfc3174.txt: a resultarray entry is not 20 bytes")

    out = []
    for i in range(4):
        name = "TEST%d" % (i + 1)
        if name not in defines:
            raise SystemExit(f"rfc3174.txt: {name} is not in the #define block")
        out.append((name, defines[name].encode("latin-1"), repeats[i],
                    digests[i]))
    return out


