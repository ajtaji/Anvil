#!/usr/bin/env python3
"""Executable gate for Anvil/Crypto/sha512.pbi - SHA-384 and SHA-512 on
AArch64.

WHY THIS FILE IS WRITTEN THE WAY IT IS

A hash has one useful kind of test: a known-answer test against answers
somebody else computed.  The bugs a 64-bit SHA-512 port can carry - an
arithmetic `>>` where FIPS 180-4 means a logical one, a signed byte read,
a stride that is not the size of the element - all produce a
deterministic, stable, WRONG digest.  Only an independent oracle sees
them.

  THREE ORACLES, NONE OF THEM THIS FILE'S LIBRARY.
    1. The FIPS 180-4 / NIST CSRC example digests ("abc" and the 112-byte
       two-block message) for SHA-384 and SHA-512, written out below as
       published.  The script checks them against the host's hashlib
       before anything runs, so a mistyped digit stops the gate rather
       than certifying a wrong answer.
    2. The host's hashlib (OpenSSL) for every other length: 0 to 300
       bytes and the padding boundaries around 112 and 128 and their
       doubles.  A different implementation, on a different machine
       model, written by somebody else.
    3. THE CONSTANTS FROM THEIR DEFINITION.  The eighty round constants
       and the sixteen initial hash words are PARSED OUT OF sha512.pbi
       and recomputed exactly - the first 64 bits of the fractional parts
       of the cube roots (K) and square roots (IV) of the first primes,
       by integer root, no floating point - so a typo in a constant is
       caught by its index rather than only as "some digest is wrong".

  STREAMING IS TESTED SEPARATELY.  Every boundary length is also fed in
  1-, 3-, 7-, 64-, 127- and 128-byte pieces, and a snapshot is taken
  mid-message, the live context destroyed by a whole other digest, and
  restored.

  --mutate rebuilds the library with one deliberate defect at a time and
  requires every one to turn the gate red.

WHAT THIS GATE DOES NOT SAY
  * That any of this runs on silicon.  tools/a64/a64_interp.py is a model
    of the instruction set, not of the BCM2711.
  * The NIST CAVP SHA384ShortMsg/LongMsg .rsp files are NOT on this disk
    (RaspberryPi4/Reference/ carries only the SHA-1 set) and this gate
    fetches nothing.  The host hashlib stands in for them on the
    variable-length sweep; drop the two .rsp files into
    RaspberryPi4/Reference/ as cavp_SHA384ShortMsg.rsp etc. and
    --cavp runs them too.

Run: py -3 tools/a64/a64_sha512_check.py
     py -3 tools/a64/a64_sha512_check.py --mutate
"""

