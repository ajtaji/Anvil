#  MUTATIONS - each must turn the gate red
# =====================================================================
MUTATIONS = [
    ("logical shift goes arithmetic",
     "ProcedureReturn (x >> n) & ((1 << (64 - n)) - 1)",
     "ProcedureReturn (x >> n)", 1,
     "FIPS 180-4 SHR and ROTR are logical; `>>` is arithmetic here"),
    ("stride 4 instead of 8",
     "#SHA512_HWORD = 8 ", "#SHA512_HWORD = 4 ", 1,
     "the hash words are .i, eight bytes apart"),
    ("signed byte read, low byte",
     "| (PeekA(blk + 7) & 255)", "| (PeekB(blk + 7))", 1,
     "PeekB sign-extends; the low byte's extension fills the word"),
    ("one wrong round constant",
     "$428A2F98, $D728AE22", "$428A2F98, $D728AE23", 1,
     "a one-bit typo in K[0]"),
    ("wrong SHA-384 initial word",
     "$CBBB9D5D, $C1059ED8", "$CBBB9D5D, $C1059ED9", 1,
     "SHA-384 differs from SHA-512 only in its IV"),
    ("padding spill test off by one",
     "If ptr > 112", "If ptr > 113", 1,
     "a 112-byte tail would have its length written over the pad"),
    ("sigma1 rotate amount",
     "Sha512Rotr(x, 61)", "Sha512Rotr(x, 60)", 1,
     "ROTR^61 in the schedule"),
    ("counter low half dropped from the bit length",
     "bitLo = Sha512CountLo << 3", "bitLo = Sha512CountLo << 2", 1,
     "the padded length is the BIT count"),
    ("snapshot counter at the wrong offset",
     "PokeI(dst + 192, Sha512CountLo)", "PokeI(dst + 184, Sha512CountLo)", 1,
     "the counter would land over the last block bytes"),
    ("SHA-384 writes the SHA-512 word count",
     "Sha512Final(dst, 6)", "Sha512Final(dst, 7)", 1,
     "a 48-byte digest must write 48 bytes: the result slots are filled "
     "with a sentinel and the 16 bytes after a SHA-384 digest must keep it"),
]
EXPECT_SURVIVE: set = set()
SENTINEL = 0xA5


def mutate():
    src = LIB.read_text(encoding="utf-8")
    s = build_script(subset=True)
    failures = 0
    print("MUTATION TEST - each defect must do what its expectation says")
    for name, old, new, count, why in MUTATIONS:
        n = src.count(old)
        if n != count:
            print("  %-44s CANNOT APPLY - anchor occurs %d times, expected %d"
                  % (name, n, count))
            failures += 1
            continue
        mut = WORK / "sha512_mut.pbi"
        mut.write_text(src.replace(old, new), encoding="utf-8")
        try:
            build("_work/sha512_mut.pbi", WORK / "sha512harness_mut.pi4",
                  WORK / "sha512check_mut.img")
            bad, _ = check(WORK / "sha512check_mut.img", s, quiet=True)
            red = len(bad) > 0
            note = "%d of %d vectors" % (len(bad), len(s.labels))
        except SystemExit as e:
            red = True
            note = "did not build or did not complete: %s" % str(e).splitlines()[0][:60]
        expect_red = name not in EXPECT_SURVIVE
        ok = red == expect_red
        print("  %-44s %-5s (%s)%s" % (name, "RED" if red else "GREEN", note,
                                       "" if ok else "  *** UNEXPECTED ***"))
        if not ok:
            failures += 1
    return failures


def resolve_compiler(requested):
    sys.path.insert(0, str(ROOT / "tools"))
    import build as anvil_build  # noqa: E402
    if requested or os.environ.get("PMF_COMPILER"):
        from pmf_compiler import resolve_compiler as _r  # noqa: E402
        return _r(requested)
    return anvil_build.find_compiler(requested)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--compiler", default=os.environ.get("PMF_COMPILER"))
    ap.add_argument("--target", choices=sorted(TARGETS), default="pi4")
    ap.add_argument("--mutate", action="store_true")
    ap.add_argument("--subset", action="store_true",
                    help="the boundary lengths only (what --mutate runs)")
    args = ap.parse_args()
    globals()["PMFC"] = resolve_compiler(args.compiler)
    apply_target(globals(), args.target)
    print("[gate] target %s - %s, image at $%08X, stack $%08X"
          % (TARGET_NAME, TARGET_WHAT, LOAD, STACK))
    WORK.mkdir(exist_ok=True)

    anchor_fips()
    bad = check_constants(LIB.read_text(encoding="utf-8"))
    if bad:
        print("THE CONSTANT TABLES DO NOT MATCH THEIR DEFINITION")
        print("\n".join(bad))
        return 1
    print("  constants: 80 K and 16 IV words match the cube/square roots "
          "of the first primes")

    t0 = time.time()
    build(LIB_REL, WORK / "sha512harness.pi4", WORK / "sha512check.img")
    if args.mutate:
        s = build_script(subset=True)
        bad, _ = check(WORK / "sha512check.img", s)
        if bad:
            print("the unmutated library already fails; fix that first")
            print("\n".join(bad[:10]))
            return 1
        return 1 if mutate() else 0
    s = build_script(subset=args.subset)
    print("SHA-384/SHA-512 gate - oracles: FIPS 180-4 examples, host hashlib, "
          "constants from their definition")
    bad, steps = check(WORK / "sha512check.img", s)
    print("  %.1f s" % (time.time() - t0))
    if bad:
        print("\nFAILURES")
        print("\n".join(bad[:40]))
        return 1
    print("OK")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
