def build(lib_include, harness, img):
    WORK.mkdir(exist_ok=True)
    harness.write_text(patch_harness(HARNESS.replace("__LIB__", lib_include),
                                     globals()), encoding="utf-8")
    cmd = [str(PMFC), "--compile", str(harness), "-t", TFLAG,
           "--load-addr", hex(LOAD), "--stack-addr", hex(STACK),
           "--entry-returns", "-o", str(img)]
    r = subprocess.run(cmd, cwd=ROOT, env=BUILD_ENV, text=True,
                       stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    if r.returncode != 0 or "pmfc: OK" not in r.stdout:
        raise SystemExit("build failed:\n" + r.stdout)


def run(img, script, count):
    blob = img.read_bytes()
    cpu = A64()
    mem = cpu.memory
    for i, b in enumerate(blob):
        mem[LOAD + i] = b
    for i, b in enumerate(script):
        mem[H_SCRIPT + i] = b
    for i in range(count * 64):
        mem[H_RESULT + i] = SENTINEL
    cpu.pc = LOAD
    cpu.sp = LOADER_SP
    cpu.x[30] = LOADER_LR
    uart = bytearray()

    def load(addr, size):
        if UART_LO <= addr <= UART_HI:
            return 0
        return sum(mem.get(addr + i, 0) << (8 * i) for i in range(size))

    def store(addr, value, size):
        if UART_LO <= addr <= UART_HI:
            if addr == UART_DR:
                uart.append(value & 0xFF)
            return
        for i in range(size):
            mem[addr + i] = (value >> (8 * i)) & 0xFF

    cpu.load = load
    cpu.store = store
    steps = 0
    while cpu.pc != LOADER_LR:
        cpu.step()
        steps += 1
        if steps > STEP_LIMIT:
            raise SystemExit("the harness never returned (%d steps)" % steps)
    if b"sha512harness done" not in uart:
        raise SystemExit("the harness returned without finishing its script:\n"
                         + uart.decode("latin-1"))
    out = []
    for i in range(count):
        a = H_RESULT + i * 64
        out.append(bytes(mem.get(a + j, 0) for j in range(64)))
    return out, steps


def pattern(n, seed):
    # Every byte value appears, bit 7 set in half of them - the bytes a
    # signed read gets wrong.
    return bytes(((i * 167 + seed * 31 + (i >> 3)) & 255) for i in range(n))


BOUNDARY = (0, 1, 55, 63, 64, 111, 112, 113, 127, 128, 129, 239, 240, 241,
            255, 256, 257)
CHUNKS = (1, 3, 7, 64, 127, 128)


def build_script(subset=False):
    s = Script()
    for name, v, msg, hexd in FIPS:
        d = bytes.fromhex(hexd)
        s.add(OP_ONESHOT, "FIPS %s %d-byte example, one shot" % (name, len(msg)),
              d, msg, variant=v)
        s.add(OP_CHUNKED, "FIPS %s %d-byte example, 1-byte pieces" % (name, len(msg)),
              d, msg, arg=1, variant=v)
    lengths = BOUNDARY if subset else range(0, 301)
    for v in (384, 512):
        for n in lengths:
            msg = pattern(n, v + n)
            s.add(OP_ONESHOT, "SHA-%d len=%d one shot" % (v, n), host(v, msg),
                  msg, variant=v)
    for v in (384, 512):
        for n in BOUNDARY:
            msg = pattern(n, v * 3 + n)
            for c in ((1, 128) if subset else CHUNKS):
                s.add(OP_CHUNKED, "SHA-%d len=%d in %d-byte pieces" % (v, n, c),
                      host(v, msg), msg, arg=c, variant=v)
            if n >= 2:
                for cut in sorted({1, n // 2, n - 1}):
                    s.add(OP_SEAM, "SHA-%d len=%d snapshot at %d" % (v, n, cut),
                          host(v, msg), msg, arg=cut, variant=v)
    if not subset:
        for v in (384, 512):
            for n in (1000, 4095):
                msg = pattern(n, n ^ v)
                s.add(OP_ONESHOT, "SHA-%d len=%d one shot" % (v, n),
                      host(v, msg), msg, variant=v)
    return s


def check(img, s, quiet=False):
    got, steps = run(img, s.done(), len(s.labels))
    bad = []
    for i, label in enumerate(s.labels):
        want = s.expect[i]
        if got[i][:len(want)] != want:
            bad.append("  %-46s expected %s\n  %-46s got      %s"
                       % (label, want.hex(), "", got[i][:len(want)].hex()))
        elif got[i][len(want):] != bytes([SENTINEL]) * (64 - len(want)):
            bad.append("  %-46s wrote past its %d-byte digest: %s"
                       % (label, len(want), got[i][len(want):].hex()))
    if not quiet:
        print("  %d vectors, %s, %d model instructions"
              % (len(s.labels), "ALL PASS" if not bad else
                 "%d FAILED" % len(bad), steps))
    return bad, steps


