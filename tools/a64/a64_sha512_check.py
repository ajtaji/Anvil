LOAD = 0x00400000
LOADER_SP = 0x00100000
LOADER_LR = 0xDEADBEE0
STACK = 0x03000000

TFLAG = "pi4"
TARGET_NAME = "pi4"
TARGET_WHAT = TARGETS["pi4"]["what"]
CONSOLE_INCLUDE = TARGETS["pi4"]["console"]

UART_LO = 0xFE201000
UART_HI = 0xFE201048
UART_DR = 0xFE201000

H_SCRIPT = 0x06000000
H_RESULT = 0x0A000000

STEP_LIMIT = 6_000_000_000

OP_END, OP_ONESHOT, OP_CHUNKED, OP_SEAM = 0, 1, 2, 3

HARNESS = r'''
; ======================================================================
;  sha512harness.pi4 - GENERATED BY tools/a64/a64_sha512_check.py.
;  NOT A SOURCE FILE. DO NOT EDIT.
; ======================================================================
XIncludeFile "RaspberryPi4/Lib/uart.pi4"
XIncludeFile "__LIB__"

#H_SCRIPT = $06000000
#H_RESULT = $0A000000

Global Dim hSnap.a[208]
Global Dim hWaste.a[64]

; variant 384 or 512 picks Begin and End; Update is shared.
Procedure HBegin(variant.i)
  If variant = 384
    Sha384Begin()
  Else
    Sha512Begin()
  EndIf
EndProcedure

Procedure HEnd(variant.i, dst.i)
  If variant = 384
    Sha384End(dst)
  Else
    Sha512End(dst)
  EndIf
EndProcedure

Procedure.i Main()
  Define p.i
  Define q.i
  Define op.i
  Define arg.i
  Define ln.i
  Define variant.i
  Define blob.i
  Define off.i
  Define n.i

  p = #H_SCRIPT
  q = #H_RESULT

  Repeat
    op      = PeekN(p)
    arg     = PeekN(p + 4)
    ln      = PeekN(p + 8)
    variant = PeekN(p + 12)
    If op = 0
      Break
    EndIf
    blob = p + 16

    If op = 1
      If variant = 384
        Sha384Of(blob, ln, q)
      Else
        Sha512Of(blob, ln, q)
      EndIf

    ElseIf op = 2
      HBegin(variant)
      off = 0
      While off < ln
        n = arg
        If off + n > ln
          n = ln - off
        EndIf
        If variant = 384
          Sha384Update(blob + off, n)
        Else
          Sha512Update(blob + off, n)
        EndIf
        off = off + n
      Wend
      HEnd(variant, q)

    ElseIf op = 3
      ; Snapshot at byte arg, DESTROY the live context with a whole other
      ; digest of the other variant, restore, finish.
      HBegin(variant)
      If arg > 0
        Sha512Update(blob, arg)
      EndIf
      If variant = 384
        Sha384Snapshot(@hSnap[0])
        Sha512Begin()
        Sha512Update(blob, ln)
        Sha512End(@hWaste[0])
        Sha384Restore(@hSnap[0])
      Else
        Sha512Snapshot(@hSnap[0])
        Sha384Begin()
        Sha384Update(blob, ln)
        Sha384End(@hWaste[0])
        Sha512Restore(@hSnap[0])
      EndIf
      If ln > arg
        Sha512Update(blob + arg, ln - arg)
      EndIf
      HEnd(variant, q)
    EndIf

    p = p + 16 + (((ln + 3) / 4) * 4)
    q = q + 64
  ForEver

  UartWriteStr("sha512harness done")
  ProcedureReturn 0
EndProcedure
'''


class Script:
    def __init__(self) -> None:
        self.buf = bytearray()
        self.labels: list[str] = []
        self.expect: list[bytes] = []

    def add(self, op, label, expect, msg=b"", arg=0, variant=512):
        self.labels.append(label)
        self.expect.append(expect)
        self.buf += struct.pack("<IIII", op, arg, len(msg), variant)
        self.buf += msg
        self.buf += b"\x00" * ((-len(msg)) % 4)

    def done(self) -> bytes:
        return bytes(self.buf) + struct.pack("<IIII", OP_END, 0, 0, 0)


