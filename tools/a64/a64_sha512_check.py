def host(variant, msg):
    return (hashlib.sha384 if variant == 384 else hashlib.sha512)(msg).digest()


def anchor_fips():
    for name, v, msg, hexd in FIPS:
        if host(v, msg) != bytes.fromhex(hexd):
            raise SystemExit("the published %s example for a %d-byte message "
                             "does not match the host hashlib - one of the two "
                             "is wrong; fix that before trusting anything"
                             % (name, len(msg)))


# =====================================================================
#  ORACLE 3 - the constants, from their definition
# =====================================================================
def primes(n):
    out, c = [], 2
    while len(out) < n:
        if all(c % p for p in out if p * p <= c):
            out.append(c)
        c += 1
    return out


def iroot(x, k):
    """floor(x ** (1/k)) for a non-negative integer, exactly."""
    if x < 2:
        return x
    r = 1 << ((x.bit_length() + k - 1) // k)
    while True:
        y = ((k - 1) * r + x // r ** (k - 1)) // k
        if y >= r:
            break
        r = y
    while (r + 1) ** k <= x:
        r += 1
    while r ** k > x:
        r -= 1
    return r


def frac64(p, k):
    # first 64 bits of the fractional part of p^(1/k)
    return iroot(p << (64 * k), k) & ((1 << 64) - 1)


def parse_table(text, label, count):
    m = re.search(r"^\s*%s:\s*$" % label, text, re.M)
    if not m:
        raise SystemExit("sha512.pbi: the label %s: is gone" % label)
    words = []
    for line in text[m.end():].splitlines():
        s = line.strip()
        if not s:
            continue
        if not s.startswith("Data.l"):
            break
        words += [int(w.strip().lstrip("$"), 16) for w in s[6:].split(",")]
    if len(words) < count * 2:
        raise SystemExit("sha512.pbi: %s has %d halves, expected %d"
                         % (label, len(words), count * 2))
    return [(words[2 * i] << 32) | words[2 * i + 1] for i in range(count)]


def check_constants(text):
    ps = primes(80)
    k = parse_table(text, "Sha512KTable", 80)
    bad = ["  K[%d] is %016X, the cube root of %d says %016X"
           % (i, k[i], ps[i], frac64(ps[i], 3))
           for i in range(80) if k[i] != frac64(ps[i], 3)]
    iv = parse_table(text, "Sha512IVTable", 16)
    want = [frac64(p, 2) for p in ps[:8]] + [frac64(p, 2) for p in ps[8:16]]
    bad += ["  IV[%d] is %016X, the square root of %d says %016X"
            % (i, iv[i], ps[i], want[i]) for i in range(16) if iv[i] != want[i]]
    return bad


