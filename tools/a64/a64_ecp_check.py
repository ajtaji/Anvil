def build(ecp_include, harness, img):
    WORK.mkdir(exist_ok=True)
    harness.write_text(patch_harness(HARNESS.replace("__ECP__", ecp_include),
                                     globals()), encoding="utf-8")
    cmd = [str(PMFC), "--compile", str(harness), "-t", TFLAG,
           "--load-addr", hex(LOAD), "--stack-addr", hex(STACK),
           "--entry-returns", "-o", str(img)]
    r = subprocess.run(cmd, cwd=ROOT, env=BUILD_ENV, text=True,
                       stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    if r.returncode != 0 or "pmfc: OK" not in r.stdout:
        raise SystemExit("build failed:\n" + r.stdout)


def run_job(args):
    img_bytes, op, curve, q, h, sig, out_n, limit = args
    cpu = A64()
    mem = cpu.memory
    for i, b in enumerate(img_bytes):
        mem[LOAD + i] = b
    rec = struct.pack("<IIIII", op, curve, len(q), len(h), len(sig)) + q + h + sig
    for i, b in enumerate(rec):
        mem[H_SCRIPT + i] = b
    for i in range(24):
        mem[H_RESULT + i] = 0xA5
    cpu.pc = LOAD
    cpu.sp = LOADER_SP
    cpu.x[30] = LOADER_LR
    uart = bytearray()

    def load(addr, size):
        if UART_LO <= addr <= UART_HI:
            return 0
        return sum(mem.get(addr + i, 0) << (8 * i) for i in range(size))

    def store(addr, value, size):
        if UART_LO <= addr <= UART_HI:
            if addr == UART_DR:
                uart.append(value & 0xFF)
            return
        for i in range(size):
            mem[addr + i] = (value >> (8 * i)) & 0xFF

    cpu.load = load
    cpu.store = store
    steps = 0
    while cpu.pc != LOADER_LR:
        cpu.step()
        steps += 1
        if steps > limit:
            return ("RUNAWAY", None, steps, b"")
    if b"ecpharness done" not in uart:
        return ("NOTDONE", None, steps, b"")
    s0, s1, s2 = struct.unpack("<QQQ", bytes(mem.get(H_RESULT + i, 0) for i in range(24)))
    out = bytes(mem.get(H_OUT + i, 0) for i in range(out_n))
    if op == OP_RAW:
        out = s2
    return (s0, s1, steps, out)


# WHICH CHECK MUST REFUSE EACH RAW RECORD (EcpRefusedAt, #ECP_AT_* in
# ecp.pi4). Read from the record's label: the label says what was done
# to the signature or key, and FIPS 186-4 6.4.2 says which check that
# lands on. A valid record must answer NONE.
AT = dict(NONE=0, SHAPE=1, SCALAR=2, KEY=3, CURVE=4, INFINITY=5, MISMATCH=6)
AT_BY_LABEL = [
    ("odd length", "SHAPE"),
    ("r = 0", "SCALAR"), ("s = 0", "SCALAR"), ("r = n", "SCALAR"),
    ("s = n", "SCALAR"), ("r + n", "SCALAR"), ("wider than the curve", "SCALAR"),
    ("x coordinate >= p", "KEY"), ("compressed prefix", "KEY"),
    ("truncated by one byte", "KEY"),
    ("off the curve", "CURVE"),
]


def expected_at(label, expect):
    if expect == 1:
        return AT["NONE"]
    for key, at in AT_BY_LABEL:
        if key in label:
            return AT[at]
    return AT["MISMATCH"]


def jobs_for(records, params, subset=False):
    """(label, op, curve, q, h, sig, expect_verdict, expect_err, kind)."""
    jobs = []
    for cid in params:
        jobs.append(("%s Montgomery setup" % CURVES[cid][0], OP_SETUP, cid,
                     b"", b"", b"", 1, None, "setup"))
    for r in records:
        if subset and r["kind"] == "full" and not r.get("subset"):
            continue
        q, h = bytes.fromhex(r["q"]), bytes.fromhex(r["hash"])
        e = r["expect"]
        jobs.append((r["label"] + " [raw]", OP_RAW, r["curve"], q, h,
                     bytes.fromhex(r["raw"]), e, 0 if e else 1, r["kind"]))
        # Every record reaches EcpVrfyRaw; the cheap ones also go through
        # the DER seam (a full-cost record through the seam would only
        # repeat the same arithmetic - the seam's own full-cost cases are
        # the as-signed and tampered ones below).
        if r["der"] and not subset and r["kind"] != "full" and "rule" not in r:
            jobs.append((r["label"] + " [DER seam]", OP_SEAM, r["curve"], q, h,
                         bytes.fromhex(r["der"]), e, 0 if e else 1, r["kind"]))
        if r.get("der_as_signed"):
            jobs.append((r["label"] + " [DER seam, as OpenSSL wrote it]", OP_SEAM,
                         r["curve"], q, h, bytes.fromhex(r["der_as_signed"]), e,
                         0 if e else 1, r["kind"]))
            if not subset:
                t = bytearray(bytes.fromhex(r["der_as_signed"]))
                t[-1] ^= 1
                jobs.append((r["label"] + " [DER seam, last byte of s flipped]",
                             OP_SEAM, r["curve"], q, h, bytes(t), 0, 1, "full"))
    # the seam still refuses an unknown curve by name, with -1
    r0 = records[0]
    jobs.append(("curve id 26 through the seam answers -1, never 0", OP_SEAM, 26,
                 bytes.fromhex(r0["q"]), bytes.fromhex(r0["hash"]),
                 bytes.fromhex(r0["der"]), M64, 2, "cheap"))
    jobs.append(("curve id 26 through EcpVrfyRaw answers -1", OP_RAW, 26,
                 bytes.fromhex(r0["q"]), bytes.fromhex(r0["hash"]),
                 bytes.fromhex(r0["raw"]), M64, 2, "cheap"))
    return jobs


def check_setup(cid, s0, s1, out, c):
    bad = []
    name = CURVES[cid][0]
    nl = CURVES[cid][3]
    m0p, m0n, got_nl = struct.unpack("<QQQ", out[:24])
    regs = struct.unpack("<%dQ" % (NREG * ECP_S), out[64:64 + NREG * ECP_S * 8])

    def reg(i):
        v = 0
        for j in range(nl):
            v |= regs[i * ECP_S + j] << (32 * j)
        return v
    p, n = c["p"], c["n"]
    R = 1 << (32 * nl)
    want = {
        "nbits": (s1, n.bit_length()),
        "limbs": (got_nl, nl),
        "-1/p mod 2^32": (m0p, (-pow(p, -1, 1 << 32)) % (1 << 32)),
        "-1/n mod 2^32": (m0n, (-pow(n, -1, 1 << 32)) % (1 << 32)),
        "p": (reg(0), p), "n": (reg(1), n),
        "b (Montgomery)": (reg(2), c["b"] * R % p),
        "R^2 mod p": (reg(4), R * R % p), "R^2 mod n": (reg(5), R * R % n),
        "R mod p": (reg(6), R % p), "R mod n": (reg(7), R % n),
        "Gx (Montgomery)": (reg(8), c["gx"] * R % p),
        "Gy (Montgomery)": (reg(9), c["gy"] * R % p),
    }
    if s0 != 1:
        bad.append("%s: EcpLoadCurve answered %r" % (name, s0))
    for k, (g, w) in want.items():
        if g != w:
            bad.append("%s %s: got %x want %x" % (name, k, g, w))
    for i in range(NREG * ECP_S):
        if regs[i] >> 32:
            bad.append("%s: register cell %d holds %x - a limb above 32 bits"
                       % (name, i, regs[i]))
            break
    return bad


def run_jobs(img, jobs, params, workers, limit=STEP_LIMIT, quiet=False):
    img_bytes = img.read_bytes()
    args = [(img_bytes, op, cv, q, h, s, 64 + NREG * ECP_S * 8 if op == OP_SETUP else 0,
             limit) for (_l, op, cv, q, h, s, _e, _r, _k) in jobs]
    bad, cost = [], {}
    with concurrent.futures.ProcessPoolExecutor(max_workers=workers) as ex:
        results = list(ex.map(run_job, args))
    for job, res in zip(jobs, results):
        label, op, cv, q, h, s, ev, er, kind = job
        s0, s1, steps, out = res
        if s0 in ("RUNAWAY", "NOTDONE"):
            bad.append("%s: %s after %d model instructions" % (label, s0, steps))
            continue
        if op == OP_SETUP:
            bad += check_setup(cv, s0, s1, out, params[cv])
            continue
        if s0 != (ev & M64):
            bad.append("%s: verdict %d (0x%X), want %d" % (label, s0 if s0 < 2**63 else s0 - 2**64, s0, ev if ev < 2**63 else -1))
        elif er is not None and s1 != er:
            bad.append("%s: last error %d, want %d" % (label, s1, er))
        elif op == OP_RAW and cv != 26 and out != expected_at(label, ev):
            bad.append("%s: refused at stage %d, want %d (#ECP_AT_*)"
                       % (label, out, expected_at(label, ev)))
        if kind == "full" and op == OP_RAW and ev == 1:
            cost.setdefault(cv, []).append(steps)
    if not quiet:
        print("  %d jobs, %s" % (len(jobs), "ALL PASS" if not bad else
                                 "%d FAILED" % len(bad)))
        for cv, st in sorted(cost.items()):
            print("  cost of one valid %s verify: min %s, max %s model "
                  "instructions (%d jobs)" % (CURVES[cv][0], f"{min(st):,}",
                                               f"{max(st):,}", len(st)))
    return bad, cost


