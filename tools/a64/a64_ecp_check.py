#!/usr/bin/env python3
"""Executable gate for Anvil/Crypto/ecp.pbi - ECDSA verification on
P-384 and P-521 - and for the route to it through ecdsa.pi4's
certificate seam EcdsaVrfy.

WHAT IS CHECKED, IN ORDER, AND AGAINST WHAT

  1. THE CURVE TABLES, BEFORE ANYTHING IS BUILT.  The p, n, b, Gx and Gy
     bytes are parsed OUT OF ecp.pi4's DataSection and compared byte for
     byte with OpenSSL's own `ecparam -name secpNNNr1 -param_enc explicit`
     (when OpenSSL is on the machine; the run says so when it is not).
     Independently of OpenSSL the gate then checks, in Python, that p and
     n are prime (Miller-Rabin, 40 rounds), that G is on the curve, that
     n*G is the point at infinity, and that p < 2n - the last being what
     makes ecp.pi4's single conditional subtraction of x(R) mod n correct.

  2. THE MONTGOMERY SETUP.  One job per curve runs EcpLoadCurve and dumps
     what it derived - -1/p and -1/n mod 2^32, R^2 mod p and mod n, b and
     G in Montgomery form, the bit length of n - and every value is
     recomputed here with Python integers.

  3. THE VECTORS: tools/fixtures/ecp_vectors.json, written by
     tools/gen_ecp_vectors.py.  OpenSSL made the signatures (throw-away
     keys); every expectation was agreed by `openssl dgst -verify` where
     the record is expressible in DER and by an independent pure-Python
     FIPS 186-4 verifier.  The gate re-runs that Python verifier on every
     record before trusting the file.  Valid signatures over SHA-256,
     SHA-384 and SHA-512; the malleated (r, n - s); the CAVP SigVer
     failure shapes (message, r, s, key changed; r or s zero, n, or wider
     than the curve); off-curve, >= p, compressed and truncated keys;
     and the two keys that drive the point addition into its special
     cases (Q = G, so G + Q is a doubling; Q = -G, so G + Q is infinity).
     Every record runs through EcpVrfyRaw (raw r || s), and every record
     with a DER form also runs through EcdsaVrfy - the seam x509 calls -
     where the expected EcdsaLastErr is checked too.

  4. THE COST.  Each job runs alone, so its instruction count is the cost
     of exactly one verification.  The full-cost jobs are summarised per
     curve: that number is what the commit and the vault quote.

  --mutate rebuilds ecp.pi4 with one defect at a time; every mutation in
  the table must turn the gate red (or, where marked, must NOT - with the
  argument written beside it).

WHAT THIS GATE DOES NOT SAY
  * Nothing about silicon.  The model is an instruction-set model.
  * Nothing about constant time: verification handles public data and
    ecp.pi4 is variable-time on purpose (see its header).
  * These are not the NIST CAVP SigVer files, which are not on this
    machine; see tools/gen_ecp_vectors.py.

Run: py -3 tools/a64/a64_ecp_check.py [--jobs N]
     py -3 tools/a64/a64_ecp_check.py --mutate
"""

