def mutate(params, workers):
    """Every mutant, against the P-384 subset, in ONE process pool.

    THE SUBSET IS P-384 ONLY, and it is chosen per mutation, not trimmed
    for speed alone: every cheap record (the range, key and encoding
    refusals), and of the full-cost ones exactly those some mutation
    needs - a valid SHA-512 signature (the hash must be truncated to 384
    bits), the Q = G and Q = -G keys (the two special cases of the point
    addition, which nothing else reaches) and one message-changed
    negative. P-521 runs the identical code with a different limb count
    and is covered by the full run, not by the sweep; a P-521 verify is
    four times the cost of a P-384 one in the model.
    """
    src = LIB.read_text(encoding="utf-8")
    recs = [r for r in json.loads(FIXTURE.read_text())["records"] if r["curve"] == 24]
    keep = {"valid, sha512", "valid, public key = G (d = 1)",
            "valid, public key = -G (d = n - 1)", "message changed"}
    for r in recs:
        r["subset"] = any(r["label"].endswith(k) for k in keep)
    jobs = [j for j in jobs_for(recs, {24: params[24]}, subset=True) if j[2] in (24, 26)]
    failures = 0
    images = []
    for idx, (name, old, new, count, expect_red, why) in enumerate(MUTATIONS):
        n = src.count(old)
        if n != count:
            print("  %-58s CANNOT APPLY (anchor x%d, expected %d)" % (name, n, count))
            failures += 1
            images.append(None)
            continue
        mp = WORK / ("ecp_mut%d.pi4" % idx)
        mp.write_text(src.replace(old, new), encoding="utf-8")
        img = WORK / ("ecp_mut%d.img" % idx)
        try:
            build("_work/" + mp.name, WORK / ("ecpharness_mut%d.pi4" % idx), img)
            images.append(img.read_bytes())
        except SystemExit as e:
            images.append("did not build: " + str(e).splitlines()[0][:50])
    print("MUTATION TEST - %d mutants x %d jobs in one pool of %d"
          % (len(MUTATIONS), len(jobs), workers))
    work = []
    for mi, img in enumerate(images):
        if isinstance(img, bytes):
            for ji, (_l, op, cv, q, h, s, _e, _r, _k) in enumerate(jobs):
                work.append((mi, ji, (img, op, cv, q, h, s, 0, 600_000_000)))
    with concurrent.futures.ProcessPoolExecutor(max_workers=workers) as ex:
        results = list(ex.map(run_job, [w[2] for w in work]))
    bad = {}
    for (mi, ji, _a), res in zip(work, results):
        label, op, cv, q, h, s, ev, er, kind = jobs[ji]
        s0, s1, steps, _out = res
        if (s0 in ("RUNAWAY", "NOTDONE") or s0 != (ev & M64)
                or (er is not None and s1 != er)
                or (op == OP_RAW and cv != 26 and _out != expected_at(label, ev))):
            bad[mi] = bad.get(mi, 0) + 1
    for mi, (name, old, new, count, expect_red, why) in enumerate(MUTATIONS):
        img = images[mi]
        if img is None:
            continue
        if isinstance(img, str):
            red, note = True, img
        else:
            red = bad.get(mi, 0) > 0
            note = "%d of %d jobs" % (bad.get(mi, 0), len(jobs))
        ok = red == expect_red
        print("  %-58s %-5s (%s)%s" % (name, "RED" if red else "GREEN", note,
                                       "" if ok else "  *** UNEXPECTED ***"))
        if not expect_red:
            print("        " + why)
        if not ok:
            failures += 1
    print("MUTATION SWEEP %s" % ("GREEN: every mutant did what its row says"
                                 if not failures else "RED: %d unexpected" % failures))
    return failures


